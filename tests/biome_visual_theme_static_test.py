"""Static contract for the biome visual system (Operação Renascimento, 30/10/2026).

Runs without Godot: python3 tests/biome_visual_theme_static_test.py
"""
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
THEME = ROOT / "scene/biomes/visual/biome_visual_theme.gd"
STYLES = ROOT / "scene/biomes/visual/biome_styles.gd"
GENERATOR = ROOT / "scene/biomes/biome_generator.gd"
REQUIRED = ["sky", "far", "mid", "mid_signs", "mid_glow", "under", "floor_tile", "catwalk_tile", "wall_tile"]


def png_size(path):
    data = path.read_bytes()
    assert data[:8] == b"\x89PNG\r\n\x1a\n", path
    return int.from_bytes(data[16:20], "big"), int.from_bytes(data[20:24], "big")


def styles():
    text = STYLES.read_text(encoding="utf-8")
    found = {}
    for sid, body in re.findall(r'&"(\w+)": \{(.*?)\n\t\},', text, re.S):
        found[sid] = {
            "dir": re.search(r'"dir": "res://([^"]+)"', body).group(1),
            "planes": re.findall(r'\["(\w+)", (-?[\d.]+),', body),
            "dressing": re.search(r'"dressing": "(\w+)"', body).group(1),
        }
    return found


class BiomeVisualTheme(unittest.TestCase):
    def test_every_biome_has_a_complete_original_pack(self):
        found = styles()
        self.assertEqual(set(found), {"lower_city_night", "industrial_forge", "lab_cryo", "core_reactor"})
        for sid, style in found.items():
            folder = ROOT / style["dir"]
            for name in REQUIRED + [p[0] for p in style["planes"]]:
                self.assertTrue((folder / f"{name}.png").is_file(), f"{sid}: {name}.png")
            self.assertEqual(png_size(folder / "floor_tile.png"), (64, 60))
            self.assertEqual(png_size(folder / "catwalk_tile.png"), (64, 20))
            self.assertEqual(png_size(folder / "wall_tile.png"), (18, 64))
            # Native-size planes drawn at 2x: 360 rows -> 720 screen rows.
            self.assertEqual(png_size(folder / "mid.png")[1], 360)
            roles = re.findall(r'"(anchor|under)"\]', STYLES.read_text(encoding="utf-8"))
            self.assertIn("anchor", roles)

    def test_each_gameplay_biome_enables_its_own_style(self):
        expected = {"lower_city/lower_city.tres": "lower_city_night", "industrial/industrial.tres": "industrial_forge",
                    "lab/lab.tres": "lab_cryo"}
        for path, sid in expected.items():
            self.assertIn(f'visual_theme = &"{sid}"', (ROOT / "scene/biomes" / path).read_text(encoding="utf-8"))
        self.assertIn('&"core_reactor", true', (ROOT / "scene/biomes/boss_stage.gd").read_text(encoding="utf-8"))

    def test_presentation_only(self):
        text = THEME.read_text(encoding="utf-8")
        for forbidden in ["RandomNumberGenerator", "randf", "randi", "CollisionShape2D.new(", "Area2D.new(",
                          "StaticBody2D.new(", "Input.", "rpc", "persistent_id", "queue_free", "set_meta(\"collision_role\""]:
            self.assertNotIn(forbidden, text)
        self.assertRegex(text, r"const BACKDROP_LAYER := -\d+")
        self.assertIn("VisualQuality.particle_scale()", text)
        self.assertIn("VisualQuality.allows_flicker()", text)

    def test_generator_hook_is_data_driven_and_after_signature(self):
        text = GENERATOR.read_text(encoding="utf-8")
        body = text[text.index("func _build_world("):text.index("func _sync_runtime_debug_visibility(")]
        self.assertLess(body.index("generation_signature = _build_generation_signature()"), body.index("_apply_visual_theme()"))
        self.assertLess(body.index("_spawn_required_content(rng, run_manager)"), body.index("_apply_visual_theme()"))
        self.assertNotIn("CITY_PRESENTATION", text)
        self.assertNotIn("lower_city_presentation.gd", text)
        self.assertNotIn("TemporaryParallax", THEME.read_text(encoding="utf-8"))

    def test_generated_styles_match_the_generator(self):
        text = STYLES.read_text(encoding="utf-8")
        self.assertTrue(text.startswith("extends RefCounted\n## GENERATED by tools/visual/biome_art.py"))

    def test_no_private_assets(self):
        for path in (THEME, STYLES):
            text = path.read_text(encoding="utf-8")
            for private in ["assets/audio/menu/", "temporary_items/pixelexplosive", "temporary_environment/architecture"]:
                self.assertNotIn(private, text)


if __name__ == "__main__":
    unittest.main()
