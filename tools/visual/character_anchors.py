"""Cyberfield playable characters — horizontal body anchors per animation frame.

Measures, in each cell of every player sheet, the horizontal centre of the torso (middle
band of the main silhouette) relative to the cell centre, and writes
entities/player_frame_anchors.gd. PlayerCharacterVisual shifts each frame by that amount
(mirrored when flipped, because AnimatedSprite2D does not mirror `offset`), so:
  * the body stays over the collision capsule instead of drifting inside a loop, and
  * turning around no longer jumps the body sideways by twice its off-centre distance.
Loop states anchor every frame; action states use one constant per animation (their first
frame), so a lunge inside an attack keeps its forward motion. Wall states are left to the
existing wall alignment. Sheets are read, never written.

    python3 -I tools/visual/character_anchors.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import character_refine as cr  # noqa: E402

OUT = cr.ROOT / "entities/player_frame_anchors.gd"
STATE_OF = {"idle": "idle", "walk_run": "walk", "jump_air_fall": "air", "attack_combo": "attack", "dash": "dash",
            "ground_slam": "ground_slam", "hurt": "hurt", "downed_death": "downed", "revive_ally": "revive"}
PER_FRAME = {"idle", "walk", "air", "downed", "revive"}


def torso_centre(cell: np.ndarray) -> float | None:
    comps = cr.components(cell[:, :, 3] > 127)
    if not comps:
        return None
    ys, xs = comps[0]
    top, bottom = ys.min(), ys.max()
    band = (ys > top + (bottom - top) * 0.3) & (ys < top + (bottom - top) * 0.7)
    return float(xs[band].mean()) - cell.shape[1] / 2.0 if band.any() else None


def main():
    table: dict[str, dict[str, list[int]]] = {}
    for character in cr.ACCENT:
        table[character] = {}
        for path in sorted((cr.ROOT / "assets/players" / character).glob("*.png")):
            key = next((k for k in STATE_OF if k in path.name), None)
            if key is None:
                continue
            sheet = np.array(Image.open(path).convert("RGBA"))
            frames = cr.frame_count(character, path)
            width = sheet.shape[1] // frames
            centres = [torso_centre(sheet[:, i * width:(i + 1) * width]) for i in range(frames)]
            centres = [c if c is not None else 0.0 for c in centres]
            state = STATE_OF[key]
            if state in PER_FRAME:
                values = [round(c) for c in centres]
            else:
                values = [round(centres[0])] * frames
            table[character][state] = values
    lines = [
        "extends RefCounted",
        "## GENERATED by tools/visual/character_anchors.py — do not edit by hand.",
        "## Horizontal torso centre of every frame, in texture pixels from the cell centre.",
        "",
        "const ANCHORS := {",
    ]
    for character, states in table.items():
        lines.append('\t&"%s": {' % character)
        for state, values in states.items():
            lines.append('\t\t&"%s": [%s],' % (state, ", ".join("%.1f" % v for v in values)))
        lines.append("\t},")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print("ok", OUT.relative_to(cr.ROOT))


if __name__ == "__main__":
    main()
